const mongoose = require("mongoose");
const { timeStamp } = require("node:console");

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
      minlength: 2,
      maxlength: 100,
    },
    email: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    password: {
      type: String,
      required: true,
      select: false,
    },
  },
  { timeStamp: true },
);

module.exports = mongoose.model("User", userSchema);
